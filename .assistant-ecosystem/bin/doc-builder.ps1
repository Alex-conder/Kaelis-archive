#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Documentation Builder for OpenClaw Assistant
.DESCRIPTION
    Generate API docs, config docs, and operation manuals
#>

$EcosystemRoot = "$env:USERPROFILE\.assistant-ecosystem"
$OutputPath = "$EcosystemRoot\docs\generated"

function Initialize-DocBuilder {
    if (-not (Test-Path $OutputPath)) {
        New-Item -ItemType Directory -Path $OutputPath -Force | Out-Null
    }
}

function Get-ScriptInfo {
    param([string]$ScriptPath)
    
    $content = Get-Content $ScriptPath -Raw
    $info = @{
        Name = Split-Path $ScriptPath -Leaf
        Synopsis = ""
        Description = ""
    }
    
    if ($content -match "\.SYNOPSIS\s*\r?\n([^#]+)") {
        $info.Synopsis = $Matches[1].Trim()
    }
    
    if ($content -match "\.DESCRIPTION\s*\r?\n([^#]+)") {
        $info.Description = $Matches[1].Trim()
    }
    
    return $info
}

function Build-APIDoc {
    Initialize-DocBuilder
    
    $scripts = Get-ChildItem "$EcosystemRoot\bin" -Filter "*.ps1"
    
    $doc = @"
# OpenClaw Assistant API Reference

Generated: $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")

## Tools Overview

Total: $($scripts.Count) tools

"@
    
    foreach ($script in ($scripts | Sort-Object Name)) {
        $info = Get-ScriptInfo -ScriptPath $script.FullName
        $doc += "### $($script.BaseName)`n`n"
        $doc += "**File**: $($script.Name)`n`n"
        $doc += "$($info.Synopsis)`n`n"
        if ($info.Description) {
            $doc += "$($info.Description)`n`n"
        }
        $doc += "---`n`n"
    }
    
    $outputFile = "$OutputPath\api-reference.md"
    $doc | Set-Content $outputFile -Encoding UTF8
    
    Write-Host "API documentation generated: $outputFile" -ForegroundColor Green
    return $outputFile
}

function Build-ToolIndex {
    Initialize-DocBuilder
    
    $scripts = Get-ChildItem "$EcosystemRoot\bin" -Filter "*.ps1" | Sort-Object Name
    
    $index = @"
# OpenClaw Assistant Tool Index

Generated: $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")

## Available Tools

| Tool | Description |
|------|-------------|
"@
    
    foreach ($script in $scripts) {
        $info = Get-ScriptInfo -ScriptPath $script.FullName
        $index += "| $($script.BaseName) | $($info.Synopsis) |`n"
    }
    
    $index += @"

## Quick Links

- [API Reference](api-reference.md)
- [Ecosystem Complete](../ECOSYSTEM_COMPLETE.md)
- [Quick Start](../QUICK_START.md)

---

Generated by doc-builder.ps1
"@
    
    $outputFile = "$OutputPath\tool-index.md"
    $index | Set-Content $outputFile -Encoding UTF8
    
    Write-Host "Tool index generated: $outputFile" -ForegroundColor Green
    return $outputFile
}

function Show-DocStatus {
    Initialize-DocBuilder
    
    Write-Host "`n[Documentation Builder Status]" -ForegroundColor Cyan
    
    $scripts = Get-ChildItem "$EcosystemRoot\bin" -Filter "*.ps1"
    Write-Host "Source scripts: $($scripts.Count)" -ForegroundColor Gray
    
    if (Test-Path $OutputPath) {
        $docs = Get-ChildItem $OutputPath -Filter "*.md"
        Write-Host "Generated docs: $($docs.Count)" -ForegroundColor Gray
        foreach ($doc in $docs) {
            Write-Host "  - $($doc.Name) ($([math]::Round($doc.Length / 1KB, 2)) KB)" -ForegroundColor Gray
        }
    }
}

# Main execution
switch ($args[0]) {
    "api" { Build-APIDoc }
    "index" { Build-ToolIndex }
    "all" {
        Build-APIDoc | Out-Null
        Build-ToolIndex | Out-Null
        Write-Host "`nAll documentation generated!" -ForegroundColor Green
    }
    "status" { Show-DocStatus }
    default {
        Write-Host "Documentation Builder for OpenClaw Assistant" -ForegroundColor Cyan
        Write-Host "Usage:" -ForegroundColor White
        Write-Host "  doc-builder.ps1 api      - Build API documentation" -ForegroundColor Gray
        Write-Host "  doc-builder.ps1 index    - Build tool index" -ForegroundColor Gray
        Write-Host "  doc-builder.ps1 all      - Build all documentation" -ForegroundColor Gray
        Write-Host "  doc-builder.ps1 status   - Show builder status" -ForegroundColor Gray
    }
}
